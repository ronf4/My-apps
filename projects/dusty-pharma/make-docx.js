function table(head, rows, widths) {
  const cell = (t, i, h) => new TableCell({
    width: { size: widths[i], type: WidthType.DXA }, borders,
    shading: h ? { type: ShadingType.CLEAR, fill: 'DCE6F2', color: 'auto' } : undefined,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: [new Paragraph({ children: [new TextRun({ text: t, font: F, size: 20, bold: h })] })],
  });
  return new Table({
    width: { size: W, type: WidthType.DXA }, columnWidths: widths,
    rows: [new TableRow({ tableHeader: true, children: head.map((t, i) => cell(t, i, true)) })]
      .concat(rows.map(r => new TableRow({ children: r.map((t, i) => cell(t, i, false)) }))),
  });
}
